"""Persistent estimated layers and reversible edits to an immutable decoded original."""
from __future__ import annotations

from copy import deepcopy
from dataclasses import asdict, dataclass, field
import json
import math
import os
from pathlib import Path
import shutil
import stat
import tempfile
from typing import Any, Mapping, Sequence
from uuid import uuid4

import numpy as np
import numpy.typing as npt

from .audio import AudioContractError, AudioData, AudioLimits, Samples, sha256_file, validate_samples


class LockedLayerError(AudioContractError):
    """A proposed update would change a locked estimate."""


def normalize_query(query: str) -> str:
    if not isinstance(query, str) or not query.strip() or len(query) > 512:
        raise AudioContractError("A layer query must contain 1 to 512 characters")
    return " ".join(query.casefold().split())


def _safe_path(root: Path, relative: str) -> Path:
    if not isinstance(relative, str) or not relative or Path(relative).is_absolute():
        raise AudioContractError("Project asset path must be relative")
    candidate = (root / relative).resolve()
    if not candidate.is_relative_to(root.resolve()) or candidate == root.resolve():
        raise AudioContractError("Project asset path leaves its project")
    return candidate


def _json_copy(value: Any) -> Any:
    try:
        encoded = json.dumps(value, allow_nan=False)
        if len(encoded) > 1024 * 1024:
            raise AudioContractError("Metadata exceeds one MiB")
        return json.loads(encoded)
    except (TypeError, ValueError) as exc:
        raise AudioContractError("Metadata must be finite JSON data") from exc


def _write_json(path: Path, content: Any) -> None:
    # Bound the document being written, not merely the previous revision. History
    # repeats metadata, so a permitted per-proposal payload can grow past this cap.
    encoded = (json.dumps(content, indent=2, allow_nan=False) + "\n").encode("utf-8")
    if len(encoded) > 32 * 1024 * 1024:
        raise AudioContractError("Next JSON document exceeds 32 MiB; transaction was not saved")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{uuid4().hex}.tmp")
    try:
        with temporary.open("xb") as stream:
            stream.write(encoded)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def _read_json(path: Path) -> Any:
    """Bound metadata bytes and native file type before reading."""
    limit = 32 * 1024 * 1024
    try:
        descriptor = os.open(path, os.O_RDONLY | os.O_NONBLOCK | getattr(os, "O_NOFOLLOW", 0))
    except OSError as exc:
        raise AudioContractError("Manifest must be a readable regular file") from exc
    with os.fdopen(descriptor, "rb") as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_size > limit:
            raise AudioContractError("Manifest must be a regular file of at most 32 MiB")
        encoded = stream.read(limit + 1)
    if len(encoded) > limit:
        raise AudioContractError("Manifest exceeds 32 MiB")
    try:
        return json.loads(encoded)
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        raise AudioContractError("Malformed JSON manifest") from exc


@dataclass(frozen=True)
class Anchor:
    start: float
    end: float
    present: bool = True

    def validate(self, duration: float) -> None:
        if (type(self.present) is not bool or not math.isfinite(self.start)
                or not math.isfinite(self.end) or not 0 <= self.start < self.end <= duration):
            raise AudioContractError("Anchor must be a valid present/absent span in the mixed recording")


@dataclass(frozen=True)
class Layer:
    id: str
    query: str
    samples: Samples
    locked: bool = False
    anchors: tuple[Anchor, ...] = ()
    metadata: dict[str, Any] = field(default_factory=dict)


class Project:
    """Methods persist atomically. Estimated stems are assets, never regenerated by edits."""

    SCHEMA = "stemscene-project/1"

    def __init__(self, root: Path, manifest: dict[str, Any], original: AudioData) -> None:
        self.root = root.resolve()
        self.original = original
        self._manifest = manifest
        self._arrays: dict[str, Samples] = {}

    @property
    def sample_rate(self) -> int:
        return self.original.sample_rate

    @property
    def limits(self) -> AudioLimits:
        return AudioLimits(**self._manifest["limits"])

    @property
    def revision(self) -> int:
        return self._manifest["revision"]

    @property
    def layers(self) -> list[Layer]:
        return [Layer(row["id"], row["query"], self._load_array(row), row["locked"],
                      tuple(Anchor(**a) for a in row["anchors"]), deepcopy(row["metadata"]))
                for row in self._manifest["layers"]]

    @property
    def edits(self) -> list[dict[str, Any]]:
        return deepcopy(self._manifest["edits"])

    @property
    def history(self) -> list[dict[str, Any]]:
        return deepcopy(self._manifest["history"])

    @classmethod
    def create(cls, source_path: str | Path, project_dir: str | Path,
               limits: AudioLimits | None = None) -> "Project":
        limits = limits or AudioLimits()
        source = Path(source_path).resolve()
        destination = Path(project_dir).absolute()
        if destination.exists():
            raise FileExistsError(f"Project destination already exists: {destination}")
        # Inspect before copying; then read the preserved copy to make its bytes authoritative.
        AudioData.read(source, limits)
        destination.parent.mkdir(parents=True, exist_ok=True)
        temporary = Path(tempfile.mkdtemp(prefix=f".{destination.name}.", dir=destination.parent))
        try:
            source_name = "original" + (".flac" if source.suffix.lower() == ".flac" else ".wav")
            preserved = temporary / source_name
            with source.open("rb") as incoming, preserved.open("xb") as outgoing:
                copied = 0
                for block in iter(lambda: incoming.read(1024 * 1024), b""):
                    copied += len(block)
                    if copied > limits.max_source_bytes:
                        raise AudioContractError("Input changed or exceeds the source byte limit")
                    outgoing.write(block)
            original = AudioData.read(preserved, limits)
            if original.samples.nbytes * 2 > limits.max_project_array_bytes:
                raise AudioContractError("Original exceeds the project array memory limit")
            manifest = {"schema": cls.SCHEMA, "id": uuid4().hex, "revision": 0,
                        "source": {"path": source_name, **original.metadata()},
                        "limits": asdict(limits), "layers": [], "edits": [], "history": [],
                        "audio_contract": {"resampling": "none in project core", "delay_samples": 0,
                                           "normalization": "none", "array_dtype": "float64",
                                           "interpretation": "estimated classes; physical identity is not guaranteed"}}
            _write_json(temporary / "project.json", manifest)
            # Rename to a destination which must remain absent; never replace an existing project.
            if destination.exists():
                raise FileExistsError(destination)
            os.rename(temporary, destination)
            return cls(destination, manifest, original)
        except BaseException:
            shutil.rmtree(temporary, ignore_errors=True)
            raise

    @classmethod
    def load(cls, project_dir: str | Path) -> "Project":
        root = Path(project_dir).resolve()
        manifest_path = root / "project.json"
        if manifest_path.stat().st_size > 32 * 1024 * 1024:
            raise AudioContractError("Project manifest exceeds 32 MiB")
        try:
            manifest = _read_json(manifest_path)
            if manifest["schema"] != cls.SCHEMA:
                raise AudioContractError("Unsupported project schema")
            limits = AudioLimits(**manifest["limits"])
            original = AudioData.read(_safe_path(root, manifest["source"]["path"]), limits)
            for key, value in original.metadata().items():
                if manifest["source"].get(key) != value:
                    raise AudioContractError("Preserved original metadata/hash mismatch")
            project = cls(root, manifest, original)
            project._validate_state(manifest)
            if not isinstance(manifest["history"], list) or len(manifest["history"]) > 100:
                raise AudioContractError("Invalid or excessive project history")
            for snapshot in manifest["history"]:
                project._validate_state(snapshot)
            return project
        except (KeyError, TypeError, json.JSONDecodeError, OverflowError) as exc:
            raise AudioContractError("Malformed project manifest") from exc

    def _validate_state(self, state: dict[str, Any]) -> None:
        rows, edits = state["layers"], state["edits"]
        if not isinstance(rows, list) or len(rows) > self.limits.max_layers:
            raise AudioContractError("Invalid layer count")
        ids, queries = set(), set()
        if self.original.samples.nbytes * (len(rows) + 2) > self.limits.max_project_array_bytes:
            raise AudioContractError("Project exceeds its array memory limit")
        for row in rows:
            if (not isinstance(row["id"], str) or len(row["id"]) != 32 or row["id"] in ids
                    or any(c not in "0123456789abcdef" for c in row["id"])):
                raise AudioContractError("Layer identifiers must be unique UUID hex strings")
            query = normalize_query(row["query"])
            if query in queries or type(row["locked"]) is not bool:
                raise AudioContractError("Duplicate query or invalid lock")
            ids.add(row["id"])
            queries.add(query)
            _json_copy(row["metadata"])
            for a in row["anchors"]:
                Anchor(**a).validate(self.original.duration)
            self._load_array(row)
        if not isinstance(edits, list) or len(edits) > 10000:
            raise AudioContractError("Invalid or excessive edit count")
        for edit in edits:
            if edit["layer_id"] not in ids:
                raise AudioContractError("Edit refers to an unknown layer")
            self._validate_edit(edit)

    def _load_array(self, row: dict[str, Any]) -> Samples:
        path = _safe_path(self.root, row["path"])
        cache_key = row["sha256"]
        if cache_key in self._arrays:
            return self._arrays[cache_key]
        expected = self.original.samples.nbytes
        if path.stat().st_size > expected + 65536:
            raise AudioContractError("Layer file exceeds its declared shape")
        if sha256_file(path, max_bytes=expected + 65536) != cache_key:
            raise AudioContractError("Layer asset checksum mismatch")
        try:
            result = validate_samples(np.load(path, mmap_mode="r", allow_pickle=False), shape=self.original.samples.shape)
        except (OSError, ValueError) as exc:
            raise AudioContractError(f"Invalid aligned layer array: {exc}") from exc
        # Bound cached current and historical assets during validation.
        if len(self._arrays) >= self.limits.max_layers:
            self._arrays.pop(next(iter(self._arrays)))
        self._arrays[cache_key] = result
        return result

    def _snapshot(self) -> dict[str, Any]:
        return deepcopy({key: self._manifest[key] for key in ("revision", "layers", "edits")})

    def _commit(self, state: dict[str, Any]) -> None:
        previous = self._manifest
        candidate = deepcopy(state)
        candidate["history"] = (deepcopy(previous["history"]) + [self._snapshot()])[-100:]
        candidate["revision"] = previous["revision"] + 1
        self._persist(candidate)
        self._manifest = candidate

    def _persist(self, candidate: dict[str, Any]) -> None:
        """Refuse concurrent/stale writers rather than lose another process's edits."""
        lock_path = self.root / ".write.lock"
        try:
            lock = lock_path.open("x")
        except FileExistsError as exc:
            raise AudioContractError("Project is being written; retry after reloading") from exc
        try:
            with lock:
                lock.write(str(os.getpid()))
                lock.flush()
                path = self.root / "project.json"
                if path.stat().st_size > 32 * 1024 * 1024:
                    raise AudioContractError("Project manifest exceeds 32 MiB")
                current = _read_json(path)
                if current != self._manifest:
                    raise AudioContractError("Project changed in another process; reload before editing")
                _write_json(path, candidate)
        finally:
            lock_path.unlink(missing_ok=True)

    def save(self) -> None:
        """Mutations already save; explicitly revalidate assets and write current state."""
        self._validate_state(self._manifest)
        self._persist(self._manifest)

    def add_estimates(self, estimates: Mapping[str, npt.ArrayLike], *,
                      anchors: Mapping[str, Sequence[Anchor]] | None = None,
                      metadata: Mapping[str, Any] | None = None) -> dict[str, str]:
        """Insert or replace unlocked estimates. Exact normalized duplicates share one id.

        A locked estimate changing even one sample is an incompatible lock and rejects
        the entire transaction. Existing edits retain their selected layer identities.
        Metadata describes the proposal method/uncertainty; it is not accuracy proof.
        """
        state = deepcopy(self._manifest)
        existing = {normalize_query(row["query"]): row for row in state["layers"]}
        requested = {normalize_query(query) for query in estimates}
        prospective_count = len(set(existing) | requested)
        if prospective_count > self.limits.max_layers:
            raise AudioContractError("Request exceeds maximum layers")
        if self.original.samples.nbytes * (prospective_count + 2) > self.limits.max_project_array_bytes:
            raise AudioContractError("Request exceeds project array memory limit")
        grouped: dict[str, tuple[str, Samples]] = {}
        for query, values in estimates.items():
            normalized = normalize_query(query)
            array = validate_samples(values, shape=self.original.samples.shape,
                                     max_bytes=self.limits.max_decoded_bytes)
            if normalized in grouped and not np.array_equal(grouped[normalized][1], array):
                raise AudioContractError("Duplicate query proposals disagree; group the request before refinement")
            grouped[normalized] = (query.strip(), array)
        if len(set(existing) | set(grouped)) > self.limits.max_layers:
            raise AudioContractError("Request exceeds maximum layers")
        if self.original.samples.nbytes * (len(set(existing) | set(grouped)) + 2) > self.limits.max_project_array_bytes:
            raise AudioContractError("Request exceeds project array memory limit")
        normalized_anchors = {normalize_query(q): list(a) for q, a in (anchors or {}).items()}
        for query_anchors in normalized_anchors.values():
            for anchor in query_anchors:
                anchor.validate(self.original.duration)
        proposal_metadata = _json_copy(dict(metadata or {}))
        # Validate all locks before writing any new assets.
        for key, (_, array) in grouped.items():
            row = existing.get(key)
            if row and row["locked"] and not np.array_equal(self._load_array(row), array):
                raise LockedLayerError(f"Locked layer {row['id']} ({row['query']}) conflicts with this proposal")
        result: dict[str, str] = {}
        changed = False
        for key, (query, array) in grouped.items():
            row = existing.get(key)
            if row is not None and np.array_equal(self._load_array(row), array):
                result[query] = row["id"]
                continue
            identifier = row["id"] if row else uuid4().hex
            relative = f"layers/{identifier}-{uuid4().hex}.npy"
            path = self.root / relative
            path.parent.mkdir(exist_ok=True)
            with path.open("xb") as stream:
                np.save(stream, array, allow_pickle=False)
            new_row = {"id": identifier, "query": row["query"] if row else query,
                       "path": relative, "sha256": sha256_file(path), "locked": False,
                       "anchors": [asdict(a) for a in normalized_anchors.get(key, [])]
                                  if key in normalized_anchors else (row["anchors"] if row else []),
                       "metadata": {"identity_scope": "estimated sound class, not a guaranteed physical source",
                                    "uncertainty": "not independently verified", **proposal_metadata}}
            if row:
                state["layers"][state["layers"].index(row)] = new_row
            else:
                state["layers"].append(new_row)
            result[query] = identifier
            changed = True
        if changed:
            self._commit(state)
        return {request: result[grouped[normalize_query(request)][0]] for request in estimates}

    def set_locked(self, layer_id: str, locked: bool = True) -> None:
        if type(locked) is not bool:
            raise AudioContractError("Lock must be boolean")
        state = deepcopy(self._manifest)
        row = self._find_row(layer_id, state)
        if row["locked"] != locked:
            row["locked"] = locked
            self._commit(state)

    def set_anchors(self, layer_id: str, anchors: Sequence[Anchor]) -> None:
        for anchor in anchors:
            anchor.validate(self.original.duration)
        state = deepcopy(self._manifest)
        self._find_row(layer_id, state)["anchors"] = [asdict(a) for a in anchors]
        self._commit(state)

    def _find_row(self, layer_id: str, state: dict[str, Any] | None = None) -> dict[str, Any]:
        for row in (state or self._manifest)["layers"]:
            if row["id"] == layer_id:
                return row
        raise AudioContractError(f"Unknown layer: {layer_id}")

    def _validate_edit(self, edit: dict[str, Any]) -> None:
        start, end, fade, gain = (edit[k] for k in ("start_sample", "end_sample", "fade_samples", "gain"))
        if (type(start) is not int or type(end) is not int or type(fade) is not int
                or not 0 <= start < end <= self.original.frames or not 0 <= fade <= (end - start) // 2
                or not isinstance(gain, (int, float)) or not math.isfinite(gain) or not 0 <= gain <= 4):
            raise AudioContractError("Invalid edit bounds, fade, or gain (allowed 0 to 4)")

    def edit(self, layer_id: str, start: float, end: float, gain: float,
             fade_seconds: float = 0.005, *, edit_id: str | None = None) -> str:
        """Add a gain operation, or replace a named saved event without stacking it."""
        self._find_row(layer_id)
        if (not all(math.isfinite(v) for v in (start, end, gain, fade_seconds))
                or not 0 <= start < end <= self.original.duration or fade_seconds < 0):
            raise AudioContractError("Edit must be a finite in-recording span")
        start_sample, end_sample = round(start * self.sample_rate), round(end * self.sample_rate)
        fade = min(round(fade_seconds * self.sample_rate), (end_sample - start_sample) // 2)
        record = {"id": edit_id or uuid4().hex, "layer_id": layer_id, "start_sample": start_sample,
                  "end_sample": end_sample, "gain": float(gain), "fade_samples": fade,
                  "fade_shape": "linear-amplitude-inside-span"}
        self._validate_edit(record)
        state = deepcopy(self._manifest)
        if edit_id is not None:
            matching = [i for i, row in enumerate(state["edits"]) if row["id"] == edit_id]
            if not matching or state["edits"][matching[0]]["layer_id"] != layer_id:
                raise AudioContractError("Saved event does not belong to the selected layer")
            state["edits"][matching[0]] = record
        else:
            if len(state["edits"]) >= 10000:
                raise AudioContractError("Project edit limit reached")
            state["edits"].append(record)
        self._commit(state)
        return record["id"]

    def remove_edit(self, edit_id: str) -> None:
        """Remove one saved gain event; undo can restore it."""
        state = deepcopy(self._manifest)
        matching = [row for row in state["edits"] if row["id"] == edit_id]
        if not matching:
            raise AudioContractError("Unknown saved event")
        state["edits"] = [row for row in state["edits"] if row["id"] != edit_id]
        self._commit(state)

    def envelope(self, layer_id: str) -> npt.NDArray[np.float64]:
        self._find_row(layer_id)
        envelope = np.ones(self.original.frames, dtype=np.float64)
        for edit in self._manifest["edits"]:
            if edit["layer_id"] != layer_id:
                continue
            start, end, fade = (edit[k] for k in ("start_sample", "end_sample", "fade_samples"))
            selected = np.full(end - start, edit["gain"], dtype=np.float64)
            if fade:
                ramp = np.linspace(1.0, edit["gain"], fade + 1)[:-1]
                selected[:fade] = ramp
                selected[-fade:] = ramp[::-1]
            envelope[start:end] *= selected
        if not np.isfinite(envelope).all():
            raise AudioContractError("Combined gain envelope overflows float64")
        return envelope

    def render(self) -> Samples:
        output = self.original.samples.copy()
        for layer in self.layers:
            delta = self.envelope(layer.id) - 1.0
            active = delta != 0
            # Do not arithmetically touch samples outside selected edit spans.
            output[active] += delta[active, None] * layer.samples[active]
        if not np.isfinite(output).all():
            raise AudioContractError("Rendered mix overflows float64")
        output.flags.writeable = False
        return output

    def residual(self) -> Samples:
        result = self.original.samples.copy()
        for layer in self.layers:
            result -= layer.samples
        if not np.isfinite(result).all():
            raise AudioContractError("Residual overflows float64")
        result.flags.writeable = False
        return result

    def undo(self) -> bool:
        """Restore the preceding persistent revision, including gains and layer identity."""
        history = self._manifest["history"]
        if not history:
            return False
        state = deepcopy(self._manifest)
        previous = deepcopy(history[-1])
        state.update(previous)
        state["history"] = deepcopy(history[:-1])
        # Revision is monotonic even though content returns to a previous state.
        state["revision"] = self._manifest["revision"] + 1
        self._persist(state)
        self._manifest = state
        return True
